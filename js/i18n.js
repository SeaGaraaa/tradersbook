// Язык интерфейса: русский (ключи) и английский (словарь). Данные пользователя (чек-лист, идеи, заметки) не переводятся.
// t("Русский текст {n}", { n }) — подставляет значения; нет перевода — остаётся русский.

const get = () => { try { return localStorage.getItem("tj.lang") === "en" ? "en" : "ru"; } catch { return "ru"; } };
export let LANG = get();

export function setLang(l) {
  LANG = l === "en" ? "en" : "ru";
  try { localStorage.setItem("tj.lang", LANG); } catch { /* приватный режим */ }
  document.documentElement.lang = LANG;
}

export function t(s, vars) {
  let r = LANG === "en" ? (EN[s] ?? s) : s;
  if (vars) r = r.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
  return r;
}

// Постоянные надписи в index.html: data-i18n (текст) и data-i18n-title (подсказка).
export function applyStatic(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-title]")) { el.title = t(el.dataset.i18nTitle); el.setAttribute("aria-label", el.title); }
}

